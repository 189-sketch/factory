import assert from 'node:assert/strict';
import test from 'node:test';
import React, {act} from 'react';
import {createRoot} from 'react-dom/client';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
test('failed cleanup requires explicit stop confirmation before retry', async context => {
 const server=await createServer({server:{middlewareMode:true,hmr:false},appType:'custom'}); context.after(()=>server.close());
 const {TaskActions}=await server.ssrLoadModule('/src/task-detail.jsx');
 const dom=new JSDOM('<div id="root"></div>');
 const previous={window:global.window,document:global.document,IS_REACT_ACT_ENVIRONMENT:global.IS_REACT_ACT_ENVIRONMENT};
 Object.assign(global,{window:dom.window,document:dom.window.document,IS_REACT_ACT_ENVIRONMENT:true});
 const root=createRoot(document.getElementById('root')); context.after(async()=>{await act(()=>root.unmount());dom.window.close();Object.assign(global,previous);});
 const job={state:'failed',recipe:'single',runs:[{id:'run',cleanup_unconfirmed:true,process_stopped:false}]};const calls=[];
 await act(()=>root.render(React.createElement(TaskActions,{job,onAction:(...args)=>calls.push(args)})));
 const retry=[...document.querySelectorAll('button')].find(b=>b.textContent==='Retry agent');
 assert.equal(retry.disabled,true);assert.match(document.body.textContent,/verified the previous worker process has stopped/);
 await act(()=>document.querySelector('input[type="checkbox"]').click());assert.equal(retry.disabled,false);
 await act(()=>retry.click());assert.equal(calls[0][1],'retry');assert.equal(calls[0][2],true);
 await act(()=>root.render(React.createElement(TaskActions,{job:{...job,runs:[{process_stopped:true}]},onAction:()=>{}})));
 assert.equal(document.querySelector('input[type="checkbox"]'),null);
});
