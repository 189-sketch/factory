import assert from "node:assert/strict";
import test from "node:test";
import React, { act } from "react";
import { createRoot } from "react-dom/client";
import { JSDOM } from "jsdom";
import { createServer } from "vite";

test("onboarding loads without mutation, shows failures, and keeps credentials out of the form", async context => {
  const dom = new JSDOM('<div id="root"></div>', { url: "http://localhost/#/setup" });
  const prior = new Map();
  for (const name of ["window", "document", "navigator", "fetch", "IS_REACT_ACT_ENVIRONMENT"]) prior.set(name, Object.getOwnPropertyDescriptor(globalThis, name));
  for (const name of ["window", "document", "navigator"]) Object.defineProperty(globalThis, name, { configurable: true, writable: true, value: dom.window[name] });
  globalThis.IS_REACT_ACT_ENVIRONMENT = true;
  const requests = [];
  let connected = false;
  let emptyRepositories = false;
  globalThis.fetch = async (url, options) => {
    requests.push({ url, options });
    if (url.endsWith("/github/start")) return { ok: false, status: 403, json: async () => ({ error: "Enable Device Flow in your GitHub App, then try again." }) };
    if (url.endsWith("/repositories") && emptyRepositories) return { ok: true, json: async () => null };
    if (url.endsWith("/repositories")) return { ok: false, status: 403, json: async () => ({ error: "Repository access was denied. Check your GitHub App installation." }) };
    if (url.endsWith("/check")) return { ok: true, json: async () => ({ state: "failed", message: "Codex authentication failed. Sign in on your execution host." }) };
    return { ok: true, json: async () => ({ github: { configured: true, connected, account: "example" }, selection: connected ? { repository: "example/repo", agent: "codex", host: "local" } : {}, repositories: [{ full_name: "example/repo" }], agents: [{ id: "codex", name: "Codex", available: true }] }) };
  };
  const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom" });
  let root = createRoot(document.getElementById("root"));
  context.after(async () => { await act(async () => root.unmount()); await server.close(); dom.window.close(); for (const [name, descriptor] of prior) { if (descriptor) Object.defineProperty(globalThis, name, descriptor); else delete globalThis[name]; } });
  const { Onboarding } = await server.ssrLoadModule("/src/onboarding.jsx");
  await act(async () => root.render(React.createElement(Onboarding, { csrfToken: "csrf" })));
  assert.equal(requests.length, 1);
  assert.equal(requests[0].options.method, undefined);
  assert.equal(document.querySelector('input[type="password"]'), null);
  await act(async () => button("Connect GitHub").click());
  assert.match(document.querySelector('[role="alert"]').textContent, /Enable Device Flow/);
  assert.equal(requests.at(-1).options.headers["X-Machinist-CSRF"], "csrf");
  connected = true;
  await act(async () => { root.unmount(); root = createRoot(document.getElementById("root")); root.render(React.createElement(Onboarding, { csrfToken: "csrf" })); });
  await act(async () => button("Run connection check").click());
  assert.match(document.body.textContent, /Codex authentication failed/);
  assert.equal(button("Start using Machinist").disabled, true);
  await act(async () => button("Back").click());
  await act(async () => button("Back").click());
  await act(async () => button("Refresh repositories").click());
  assert.match(document.querySelector('[role="alert"]').textContent, /Repository access was denied/);
  emptyRepositories = true;
  await act(async () => button("Refresh repositories").click());
  assert.match(document.body.textContent, /No repositories available/);
  assert.equal(document.querySelectorAll("select option").length, 1);
  assert.equal(document.querySelector('[role="alert"]'), null);
  assert.ok(!requests.some(request => request.url === "/api/v1/jobs"));
});
function button(text) { const found = [...document.querySelectorAll("button")].find(item => item.textContent.trim() === text); assert.ok(found, text); return found; }
